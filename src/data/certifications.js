/**
 * Turn a Google Drive share link into a direct preview URL for <img>.
 * Works when the file is shared as "Anyone with the link".
 */
export function drivePreviewUrl(shareUrl) {
  const match = shareUrl?.match(/\/d\/([^/]+)/);
  if (!match) return shareUrl;
  return `https://drive.google.com/thumbnail?id=${match[1]}&sz=w1200`;
}

function cert({
  id,
  title,
  org,
  duration,
  skills,
  desc,
  link,
  cardBg,
  fallback,
  featured = false,
}) {
  return {
    id,
    title,
    org,
    duration,
    skills,
    desc,
    image: drivePreviewUrl(link),
    fallbackImage: badgeFallback[fallback] ?? webBadge,
    cardBg,
    link,
    featured,
  };
}

